export type IconName = keyof typeof PATHS | (string & {});

/** Creates an SVG icon at the requested size. */
export function icon(name: IconName, size = 16): SVGSVGElement {
  const svg = document.createElementNS("http://www.w3.org/2000/svg", "svg");
  svg.setAttribute("viewBox", "0 0 16 16");
  svg.setAttribute("width", String(size));
  svg.setAttribute("height", String(size));
  svg.setAttribute("fill", "currentColor");
  svg.setAttribute("aria-hidden", "true");
  svg.classList.add("icon");

  for (const part of PATHS[name] ?? PATHS["file"]!) {
    const path = document.createElementNS("http://www.w3.org/2000/svg", "path");
    path.setAttribute("d", part.d);
    if (part.rule) path.setAttribute("fill-rule", part.rule);
    svg.appendChild(path);
  }
  return svg;
}

/** Icon inside a coloured pill, for panel headers. */
export function iconChip(
  name: IconName,
  tone: "violet" | "amber" | "cyan" | "green" | "red" = "violet",
): HTMLElement {
  const chip = document.createElement("span");
  chip.className = `iconchip iconchip--${tone}`;
  chip.appendChild(icon(name, 15));
  return chip;
}
